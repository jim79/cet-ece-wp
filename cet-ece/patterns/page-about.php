<h2 class="wp-block-heading">Golden Jubilee</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The department marked its Golden Jubilee in 2015 with a year of programmes for students and faculty rather than celebrations: an alumni lecture series, workshops, exhibitions and a project exposition. The Chief Minister of Kerala inaugurated the year on 9 September 2015 and laid the foundation stone of the Golden Jubilee PG and Research Block, which opened in 2023. The M.Tech programme in Micro and Nano Electronics was launched the same day.</p>
