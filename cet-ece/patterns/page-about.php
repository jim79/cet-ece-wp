<!-- wp:paragraph -->
<p>The Department of Electronics and Communication Engineering was established at the CET campus, Sreekariyam, in 1964–65. The B.Tech programme in Electronics and Communication Engineering started with an intake of 33 students.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Today the department offers B.Tech programmes in Electronics and Communication Engineering and in Applied Electronics and Instrumentation; M.Tech programmes in Applied Electronics and Instrumentation, Communication Systems, Signal Processing, Micro and Nano Electronics, and Robotics and Automation; and a doctoral programme. All programmes are approved by AICTE, and the department is an approved QIP centre.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
