<p>The department library supports the B.Tech, M.Tech and Ph.D. programmes. It began as a small reference collection given by the teaching faculty. In 1993 it became a full library with separate lending and reference sections, using funds from the IMPACT project; later purchases came from the NETWORK and TEQIP projects.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In 2013 the library was renovated and air-conditioned with a contribution from the alumni batch of 1983–88. It is dedicated to the memory of their classmate Dr. Suresh Kumar R., who taught in the department before leaving for research in the USA.</p>
