<p>We want everyone to be able to use this website, including people who use screen readers, keyboard navigation or magnification.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What we do</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Pages follow the Web Content Accessibility Guidelines (WCAG) 2.2 at level AA as the target.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Text and background colours meet contrast requirements in light and dark mode.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Every page works with a keyboard and has a skip-to-content link.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Photos carry text descriptions, and posters have their text written out in the post.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Known gaps</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Some older PDF documents are scanned images and cannot be read by screen readers. Ask us for an accessible copy.</p>
<!-- /wp:paragraph -->

