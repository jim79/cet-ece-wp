<h2 id="outcomes" class="wp-block-heading">Outcomes</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Programme educational objectives (PEOs)</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>PEO1:</strong> Build successful professional career in industry and academic institutions as engineers, managers and academicians.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>PEO2:</strong> Develop solutions to engineering problems through innovation and research.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>PEO3:</strong> Strive for the betterment of society by proposing solutions to engineering problems or as entrepreneurs.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>PEO4:</strong> Uphold good ethical practices, right professional conduct and provide responsible team leadership.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Programme specific outcomes (PSOs)</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>PSO1 (Domain knowledge):</strong> The ability to apply the knowledge of basic science and engineering to understand various real world problems of Electronics and Communication engineering systems using sustainable technologies demonstrating the practice of professional ethics and the concerns for societal and environmental well-being.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>PSO2 (Application skill):</strong> The ability to apply domain knowledge to design and solve the state of the art requirements of Electronics industry with good interpersonal skills as a leader in a team in appreciation of professional ethics and societal responsibilities.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>PSO3 (Research):</strong> Excellent adaptability to changing work environment by selecting and applying cutting edge engineering hardware and software tools to analyze and improve systems/processes for a variety of applications as well as to interpret/synthesize the simulated and experimental data leading to valid conclusions aimed at the furtherance of research activities for the well-being of humanity.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

